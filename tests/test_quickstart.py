def test_quickstart_cli_smoke(tmp_path, capsys):
    from housekeeper.cli import main

    root = _drive(tmp_path)
    code = main(["--workspace", str(tmp_path / "cli_ws"), "quickstart", str(root), "--no-reports"])
    assert code == 0
    out = capsys.readouterr().out
    assert "Quickstart complete" in out
    assert "nothing was moved or deleted" in out
